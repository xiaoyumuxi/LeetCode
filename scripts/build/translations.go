// Build-time generator. The packaged page needs no fetch or remote resources.
package main

import (
	"encoding/json"
	"github.com/xiaoyumuxi/LeetCode/internal/plugin"
	"os"
)

func main() {
	data, err := json.Marshal(plugin.Translations())
	if err != nil {
		panic(err)
	}
	data = append([]byte("// Generated by scripts/build/translations.go.\nwindow.leetcodeMessages = "), data...)
	data = append(data, ';', '\n')
	if len(os.Args) == 2 && os.Args[1] == "--check" {
		actual, err := os.ReadFile("ui/messages.js")
		if err != nil || string(actual) != string(data) {
			os.Exit(1)
		}
		return
	}
	if err = os.WriteFile("ui/messages.js", data, 0644); err != nil {
		panic(err)
	}
}
